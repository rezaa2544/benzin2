export const PROVINCE_NAMES: readonly string[] = IRAN_PROVINCES.map((p) => p.nameFa);

/** Where a listing sits when the user has not picked a place yet. */
export const DEFAULT_PLACE = { province: 'تهران', county: 'تهران' } as const;

export interface Place {
  readonly province: string;
  readonly county: string;
}

/** Counties of a province; an unknown province yields an empty list, never a throw. */
export function countiesOf(province: string): readonly string[] {
  return IRAN_PROVINCES.find((item) => item.nameFa === province)?.counties ?? [];
}

/** True only for a real province/county pair, so the API can reject typos. */
export function isValidPlace(province: string, county: string): boolean {
  return countiesOf(province).includes(county);
}

/** Human label used by the market header: «تهران، تهران» or just the province. */
export function placeLabelFa(place: { province?: string | null; county?: string | null }): string {
  const parts = [place.province, place.county].filter((part): part is string => Boolean(part));
  return parts.join('، ');
}
